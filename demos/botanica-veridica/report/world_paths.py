def project_equirect(lon: float, lat: float, x0: float, y0: float, w: float, h: float) -> tuple[float, float]:
    """Map (lon in [-180, 180], lat in [-60, 82]) to SVG viewport coordinates."""
    lat_min, lat_max = -58.0, 80.0
    px = x0 + ((lon + 180.0) / 360.0) * w
    py = y0 + ((lat_max - max(lat_min, min(lat_max, lat))) / (lat_max - lat_min)) * h
    return px, py


def continents_svg_paths(x0: float, y0: float, w: float, h: float) -> str:
    parts = []
    for poly in CONTINENTS:
        pts = [project_equirect(lon, lat, x0, y0, w, h) for lon, lat in poly]
        d = "M " + " L ".join(f"{x:.1f},{y:.1f}" for x, y in pts) + " Z"
        parts.append(f'<path d="{d}" fill="#E6E0D2" stroke="#C5BCAE" stroke-width="0.65" />')
    return "\n".join(parts)
